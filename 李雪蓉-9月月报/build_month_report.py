TITLE_FONT = Font(name="微软雅黑", size=14, bold=True)
SEC_FONT = Font(name="微软雅黑", size=11, bold=True, color="FFFFFF")
SEC_FILL = PatternFill("solid", fgColor="2F5597")
HEAD_FONT = Font(name="微软雅黑", size=10, bold=True)
HEAD_FILL = PatternFill("solid", fgColor="D9E2F3")
BODY_FONT = Font(name="微软雅黑", size=10)
SMALL_FONT = Font(name="微软雅黑", size=9, color="808080")
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
WRAP = Alignment(wrap_text=True, vertical="top")
CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)


def section(ws, row, text, ncols):
    ws.cell(row=row, column=1, value=text).font = SEC_FONT
    for c in range(1, ncols + 1):
        ws.cell(row=row, column=c).fill = SEC_FILL
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    ws.cell(row=row, column=1).alignment = Alignment(vertical="center")
    ws.row_dimensions[row].height = 22
    return row + 1


def table(ws, row, headers, rows, widths):
    for i, h in enumerate(headers, start=1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = HEAD_FONT
        c.fill = HEAD_FILL
        c.alignment = CENTER
        c.border = BORDER
    ws.row_dimensions[row].height = 20
    row += 1
    for r in rows:
        for i, v in enumerate(r, start=1):
            c = ws.cell(row=row, column=i, value=v)
            c.font = BODY_FONT
            c.alignment = WRAP
            c.border = BORDER
        row += 1
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    return row


