export const mockTopics = (d) => ({
  topics: ANGLES.map((a) => ({
    label: a.key,          // 演示模式也给标签，界面上才看得出这一栏长什么样
    title: a.title(d.subject),
    angle: a.angle,
    hook: a.hook(d.subject),
    outline: a.outline(d.subject),
    audience_fit: d.audience ? `${d.audience}中${a.fit}` : a.fit,
  })),
});

export function mockContent(d, topic) {
  const p = platformSpec(d.platform);
  const body = (topic.outline || []).map((point, i) => `## ${i + 1}. ${point}

**结论**：这里给出这一节的判断句。配置模型密钥后，这一段会按「${d.tone}」的风格写成完整论证。

**依据**：列出支撑上述判断的数据、政策条款或案例，并标注口径、时间与来源；没有出处的部分会显式标注为假设。`).join('\n\n');

  return `# ${topic.title}

**核心判断**：${topic.hook}

${body}

## 风险与不确定性

${topic.angle}。上面的判断在以下情形下不成立：统计口径发生变化、关键假设未兑现、或政策与竞争条件出现反转。需要持续观察的信号与验证方式在此列明。

---
*演示模式输出 · 目标体裁：${p.label} · 风格：${d.tone}（${toneSpec(d.tone)}）· 目标篇幅约 ${d.length} 字 · 在 .env 中配置模型密钥即可生成真实报告。*
`;
}
